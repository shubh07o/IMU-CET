def run_import():
    year = 2025
    section = "General Aptitude, Reasoning & GK"
    print(f"Importing {len(questions)} questions for {year} - {section}...")
    for q in questions:
        add_question(
            year=year,
            section=section,
            question_text=q["question_text"],
            option_a=q["option_a"],
            option_b=q["option_b"],
            option_c=q["option_c"],
            option_d=q["option_d"],
            correct_option=q["correct_option"],
            explanation=q["explanation"],
            topic=q["topic"],
            difficulty=q["difficulty"],
            question_number=q["question_number"],
            q_id=q["q_id"]
        )
    export_to_json(year)
    print("Import complete! Current Stats across all years:")
    for stat in get_stats():
        print(f"Year: {stat['year']} | Section: {stat['section']} | Questions: {stat['count']}")

if __name__ == "__main__":
    run_import()
