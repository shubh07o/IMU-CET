def run_import():
    year = 2026
    shift = "Shift 1"
    section = "English"
    print(f"Importing {len(english_questions)} questions for {year} ({shift}) - {section}...")
    for q in english_questions:
        add_question(
            year=year,
            shift=shift,
            section=section,
            question_text=q["question_text"],
            option_a=q["option_a"],
            option_b=q["option_b"],
            option_c=q["option_c"],
            option_d=q["option_d"],
            correct_option=q["correct_option"],
            explanation=q["explanation"],
            topic=q["topic"],
            difficulty=q["difficulty"],
            question_number=q["question_number"],
            q_id=q["q_id"]
        )
    export_to_json(year)
    print("Import complete! Current Stats across all years & shifts:")
    for stat in get_stats():
        print(f"Year: {stat['year']} | Shift: {stat['shift']} | Section: {stat['section']} | Questions: {stat['count']}")

if __name__ == "__main__":
    run_import()
